create table if not exists public.teacher_subjects (
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (teacher_id, subject_id)
);

create index if not exists teacher_subjects_teacher_idx on public.teacher_subjects(teacher_id);
create index if not exists teacher_subjects_subject_idx on public.teacher_subjects(subject_id);

alter table public.teacher_subjects enable row level security;

-- سياسات قراءة/إدارة متوافقة مع مستخدمي المنصة المسجلين.
-- إذا كانت لديكم سياسات أكثر تقييدًا في المشروع، راجعيها قبل الاعتماد النهائي.
drop policy if exists "teacher_subjects_read_authenticated" on public.teacher_subjects;
create policy "teacher_subjects_read_authenticated"
on public.teacher_subjects for select
to authenticated
using (true);

